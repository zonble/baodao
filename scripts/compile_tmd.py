#!/usr/bin/env python3
"""
Compile docs/level*.tmd files into compact Web Audio note sequences in js/bgmData.js.
Uses `tmd` CLI tool to export MIDI, then parses MIDI into precise note schedules.
"""

import os
import re
import glob
import json
import subprocess
import tempfile

def read_vlq(data, pos):
    val = 0
    while True:
        b = data[pos]
        pos += 1
        val = (val << 7) | (b & 0x7F)
        if not (b & 0x80):
            break
    return val, pos

def parse_midi_notes(midi_bytes):
    data = midi_bytes
    pos = 10
    tracks = int.from_bytes(data[pos:pos+2], "big")
    division = int.from_bytes(data[pos+2:pos+4], "big")
    pos += 4

    tempo_events = []
    all_tracks_events = []

    for trk_idx in range(tracks):
        assert data[pos:pos+4] == b"MTrk"
        trk_len = int.from_bytes(data[pos+4:pos+8], "big")
        pos += 8
        trk_end = pos + trk_len

        events = []
        cur_time = 0
        running_status = None

        while pos < trk_end:
            dt, pos = read_vlq(data, pos)
            cur_time += dt
            b = data[pos]
            if b & 0x80:
                status = b
                pos += 1
            else:
                status = running_status
            running_status = status

            event_type = status & 0xF0
            channel = status & 0x0F

            if status == 0xFF:
                meta_type = data[pos]
                pos += 1
                meta_len, pos = read_vlq(data, pos)
                meta_data = data[pos:pos+meta_len]
                pos += meta_len
                if meta_type == 0x51: # Set Tempo
                    us = int.from_bytes(meta_data, "big")
                    tempo_events.append((cur_time, us))
            elif event_type in (0x80, 0x90):
                note = data[pos]
                vel = data[pos+1]
                pos += 2
                is_on = (event_type == 0x90 and vel > 0)
                events.append((cur_time, "on" if is_on else "off", channel, note, vel))
            elif event_type in (0xA0, 0xB0, 0xE0):
                pos += 2
            elif event_type in (0xC0, 0xD0):
                pos += 1

        all_tracks_events.append(events)

    us_per_quarter = tempo_events[0][1] if tempo_events else 500000

    def ticks_to_seconds(ticks):
        return (ticks / division) * (us_per_quarter / 1000000.0)

    notes = []
    for trk_idx, events in enumerate(all_tracks_events):
        active_notes = {}
        for t_ticks, kind, ch, note, vel in events:
            sec = ticks_to_seconds(t_ticks)
            if kind == "on":
                active_notes[note] = (sec, vel)
            elif kind == "off" and note in active_notes:
                start_sec, on_vel = active_notes.pop(note)
                dur = sec - start_sec
                freq = 440.0 * (2.0 ** ((note - 69) / 12.0))
                notes.append({
                    "trk": trk_idx,
                    "t": round(start_sec, 3),
                    "dur": round(dur, 3),
                    "note": note,
                    "freq": round(freq, 2),
                    "vel": round(on_vel / 127.0, 2)
                })

    notes.sort(key=lambda n: n["t"])
    total_dur = max(n["t"] + n["dur"] for n in notes) if notes else 0.0
    return notes, round(total_dur, 2)

def main():
    docs_dir = "docs"
    output_js = "js/bgmData.js"

    tmd_files = sorted(glob.glob(os.path.join(docs_dir, "level*.tmd")))
    if not tmd_files:
        print("No TMD files found in", docs_dir)
        return

    bgm_map = {}

    for fpath in tmd_files:
        m = re.search(r"level(\d+)\.tmd", os.path.basename(fpath))
        if not m:
            continue
        level_idx = int(m.group(1)) - 1 # 0-indexed stage

        with tempfile.NamedTemporaryFile(suffix=".mid", delete=False) as tmp:
            tmp_mid = tmp.name

        try:
            # Run tmd compiler to export MIDI
            subprocess.run(["tmd", fpath, "-m", tmp_mid], check=True, stdout=subprocess.DEVNULL)
            with open(tmp_mid, "rb") as mf:
                midi_bytes = mf.read()
            notes, total_dur = parse_midi_notes(midi_bytes)
            bgm_map[level_idx] = {
                "source": os.path.basename(fpath),
                "duration": total_dur,
                "notes": notes
            }
            print(f"✓ Compiled {fpath} (Stage {level_idx + 1}): {len(notes)} notes, {total_dur}s")
        finally:
            if os.path.exists(tmp_mid):
                os.remove(tmp_mid)

    # Format JS file
    lines = [
        "// Auto-generated by scripts/compile_tmd.py. DO NOT EDIT DIRECTLY.",
        "// Re-generate using: python3 scripts/compile_tmd.py",
        "",
        "// Compact note unpacker: [t, dur, freq, vel, trk] -> { t, dur, freq, vel, trk }",
        "const unpackBgm = (notes) => notes.map(([t, dur, freq, vel, trk]) => ({ t, dur, freq, vel, trk }));",
        "",
        "export const TMD_BGM = {"
    ]

    for lvl_idx, data in sorted(bgm_map.items()):
        lines.append(f"  {lvl_idx}: {{")
        lines.append(f"    source: {json.dumps(data['source'])},")
        lines.append(f"    duration: {data['duration']},")
        lines.append("    notes: unpackBgm([")

        chunks = []
        for n in data["notes"]:
            chunks.append(f"      [{n['t']},{n['dur']},{n['freq']},{n['vel']},{n['trk']}]")
        lines.append(",\n".join(chunks))
        lines.append("    ])")
        lines.append("  },")

    lines.append("};")
    lines.append("")

    with open(output_js, "w", encoding="utf-8") as out:
        out.write("\n".join(lines))

    print(f"★ Generated {output_js} with {len(bgm_map)} TMD soundtracks.")

if __name__ == "__main__":
    main()
