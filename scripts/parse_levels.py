#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
scripts/parse_levels.py
-----------------------
Parser script that compiles markdown level files (docs/level*.md)
into compact JavaScript game data (js/levelData.js).

Usage:
    python3 scripts/parse_levels.py
    python3 scripts/parse_levels.py --help
"""

import os
import re
import sys
import glob
import json
import argparse
import unicodedata

def display_width(ch: str) -> int:
    """Return monospace display width for a unicode character (East Asian width)."""
    return 2 if unicodedata.east_asian_width(ch) in ("F", "W") else 1

def format_coords(points, indent=4, per_line=12):
    """Format a list of [r, c] points compactly with multiple pairs per line."""
    if not points:
        return "[]"
    lines = []
    chunk = []
    for pt in points:
        chunk.append(f"[{pt[0]},{pt[1]}]")
        if len(chunk) >= per_line:
            lines.append(" " * indent + ",".join(chunk))
            chunk = []
    if chunk:
        lines.append(" " * indent + ",".join(chunk))
    return "[\n" + ",\n".join(lines) + "\n" + " " * (indent - 2) + "]"

def parse_level_file(filepath: str) -> dict:
    """Parse a single docs/levelX.md file into structured level data."""
    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()

    lines = [l.rstrip("\r\n") for l in content.splitlines()]
    grid = [l[1:-1] for l in lines if l.startswith("│") and l.endswith("│")]

    if not grid:
        raise ValueError(f"No grid rows found in {filepath} (expected lines enclosed in │...│)")

    # Extract metadata from text below grid
    boss_match = re.search(r"(?:第[一二三四五六七八九十0-9]+關)?魔王[：:]\s*(.+)", content)
    bg_match = re.search(r"(?:第[一二三四五六七八九十0-9]+關)?背景[：:]\s*(.+)", content)
    boss_name = boss_match.group(1).strip() if boss_match else "關卡魔王"
    bg_theme = bg_match.group(1).strip() if bg_match else "台灣風情"

    # Identify boss boxes ┌──────┐ ... └──────┘
    boss_boxes = []
    for r, row in enumerate(grid):
        col = 0
        i = 0
        while i < len(row):
            ch = row[i]
            w = display_width(ch)
            if ch == "┌":
                end_i = row.find("┐", i)
                if end_i != -1:
                    box_w = 0
                    for c_ch in row[i:end_i+1]:
                        box_w += display_width(c_ch)
                    boss_boxes.append({"r": r, "c": col, "w": box_w, "h": 3})
            col += w
            i += 1

    terrain = []
    enemiesX = []
    enemiesS = []
    turrets = []
    traps = []
    playerStart = {"r": 4, "c": 1}

    # Extract entities
    for r, row in enumerate(grid):
        col = 0
        i = 0
        while i < len(row):
            ch = row[i]
            w = display_width(ch)

            if ch == "-" and i + 1 < len(row) and row[i+1] == ">":
                playerStart = {"r": r, "c": col}
                i += 2
                col += 2
                continue
            elif ch == ">" and i > 0 and row[i-1] == "-":
                i += 1
                col += 1
                continue
            elif ch == "e":
                terrain.append([r, col])
            elif ch == "x":
                enemiesX.append([r, col])
            elif ch == "s":
                enemiesS.append([r, col])
            elif ch == "塔":
                turrets.append([r, col])
            elif ch == "|":
                traps.append([r, col])

            col += w
            i += 1

    primary_boss = boss_boxes[0] if boss_boxes else {"r": 3, "c": 88, "w": 8, "h": 3}

    # Name multi-bosses if applicable
    if len(boss_boxes) > 1:
        for idx, b in enumerate(boss_boxes):
            b["id"] = f"sub_{idx + 1}"
            b["name"] = f"{boss_name} (#{idx + 1})"

    return {
        "cols": 99,
        "rows": len(grid),
        "bossName": boss_name,
        "bgTheme": bg_theme,
        "playerStart": playerStart,
        "boss": primary_boss,
        "bosses": boss_boxes,
        "terrain": terrain,
        "enemiesX": enemiesX,
        "enemiesS": enemiesS,
        "turrets": turrets,
        "traps": traps
    }

def generate_level_data_js(levels_data: list) -> str:
    """Generate the contents of js/levelData.js using compact coordinate representation."""
    js_lines = [
        "// Auto-generated by scripts/parse_levels.py. DO NOT EDIT DIRECTLY.",
        "// Re-generate using: python3 scripts/parse_levels.py",
        "",
        "// Compact coordinate unpacker: [r, c] -> { r, c }",
        "const unpack = (pts) => pts.map(([r, c]) => ({ r, c }));",
        ""
    ]

    var_names = []
    for idx, data in enumerate(levels_data):
        lvl_num = idx + 1
        var_name = f"LEVEL_{lvl_num}_DATA"
        var_names.append(var_name)

        boss_json = json.dumps(data["boss"])
        bosses_json = json.dumps(data["bosses"])
        start_json = json.dumps(data["playerStart"])

        js_lines.append(f"export const {var_name} = {{")
        js_lines.append(f"  cols: {data['cols']},")
        js_lines.append(f"  rows: {data['rows']},")
        js_lines.append(f"  bossName: {json.dumps(data['bossName'], ensure_ascii=False)},")
        js_lines.append(f"  bgTheme: {json.dumps(data['bgTheme'], ensure_ascii=False)},")
        js_lines.append(f"  playerStart: {start_json},")
        js_lines.append(f"  boss: {boss_json},")
        js_lines.append(f"  bosses: {bosses_json},")
        js_lines.append(f"  terrain: unpack({format_coords(data['terrain'], indent=4, per_line=12)}),")
        js_lines.append(f"  enemiesX: unpack({format_coords(data['enemiesX'], indent=4, per_line=12)}),")
        js_lines.append(f"  enemiesS: unpack({format_coords(data['enemiesS'], indent=4, per_line=12)}),")
        js_lines.append(f"  turrets: unpack({format_coords(data['turrets'], indent=4, per_line=12)}),")
        js_lines.append(f"  traps: unpack({format_coords(data['traps'], indent=4, per_line=12)})")
        js_lines.append("};")
        js_lines.append("")

    all_levels_str = ", ".join(var_names)
    js_lines.append(f"export const LEVELS = [ {all_levels_str} ];")
    js_lines.append(f"export const LEVEL_DATA = {var_names[0]}; // Default stage")
    js_lines.append("")

    return "\n".join(js_lines)

def main():
    parser = argparse.ArgumentParser(description="Compile docs/level*.md maps into js/levelData.js")
    parser.add_argument("--docs-dir", default="docs", help="Path to docs directory (default: docs)")
    parser.add_argument("--output-js", default="js/levelData.js", help="Output JS path (default: js/levelData.js)")
    parser.add_argument("--output-json", default=None, help="Optional output JSON path")
    parser.add_argument("--quiet", action="store_true", help="Suppress logging output")
    args = parser.parse_args()

    pattern = os.path.join(args.docs_dir, "level*.md")
    files = glob.glob(pattern)

    # Sort numerically by level number (level1, level2, level3...)
    def get_level_number(fpath):
        m = re.search(r"level(\d+)\.md", os.path.basename(fpath))
        return int(m.group(1)) if m else 9999

    level_files = sorted([f for f in files if re.search(r"level\d+\.md", os.path.basename(f))], key=get_level_number)

    if not level_files:
        print(f"Error: No level files found in pattern {pattern}", file=sys.stderr)
        sys.exit(1)

    levels_data = []
    for fp in level_files:
        lvl_data = parse_level_file(fp)
        levels_data.append(lvl_data)
        if not args.quiet:
            print(f"✓ Parsed {fp}: {lvl_data['bossName']} ({lvl_data['bgTheme']}) | "
                  f"Terrain: {len(lvl_data['terrain'])}, "
                  f"EnemiesX: {len(lvl_data['enemiesX'])}, "
                  f"EnemiesS: {len(lvl_data['enemiesS'])}, "
                  f"Turrets: {len(lvl_data['turrets'])}, "
                  f"Traps: {len(lvl_data['traps'])}, "
                  f"Bosses: {len(lvl_data['bosses'])}")

    # Generate and write JS
    js_content = generate_level_data_js(levels_data)
    os.makedirs(os.path.dirname(os.path.abspath(args.output_js)), exist_ok=True)
    with open(args.output_js, "w", encoding="utf-8") as f:
        f.write(js_content)

    line_count = len(js_content.splitlines())
    byte_size = len(js_content.encode("utf-8"))

    if not args.quiet:
        print(f"\n★ Generated {args.output_js} ({line_count} lines, {byte_size / 1024:.1f} KB)")

    # Optional JSON output
    if args.output_json:
        os.makedirs(os.path.dirname(os.path.abspath(args.output_json)), exist_ok=True)
        with open(args.output_json, "w", encoding="utf-8") as f:
            json.dump(levels_data, f, ensure_ascii=False, indent=2)
        if not args.quiet:
            print(f"★ Generated {args.output_json}")

if __name__ == "__main__":
    main()
